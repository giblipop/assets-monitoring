-- Authentication tables for inventory. Safe to run multiple times.
USE inventory;

CREATE TABLE IF NOT EXISTS Users (
  UserID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EmployeeID VARCHAR(80) NOT NULL UNIQUE,
  AccountID CHAR(9) NULL,
  FirstName VARCHAR(100) NOT NULL,
  LastName VARCHAR(100) NOT NULL,
  Department VARCHAR(150) NOT NULL,
  WorkArea VARCHAR(150) NOT NULL,
  LanguagePreference ENUM('en','ko') NOT NULL DEFAULT 'en',
  Username VARCHAR(80) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  MustChangePassword TINYINT(1) NOT NULL DEFAULT 0,
  DateCreated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Status ENUM('active','disabled') NOT NULL DEFAULT 'active',
  UNIQUE KEY uq_users_account_id (AccountID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS LoginHistory (
  LoginID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  UserID BIGINT UNSIGNED NULL,
  LoginDateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LastActivity DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LogoutDateTime DATETIME NULL,
  DeviceName VARCHAR(255) NOT NULL,
  DeviceType VARCHAR(32) NOT NULL,
  OperatingSystem VARCHAR(80) NOT NULL,
  Browser VARCHAR(80) NOT NULL,
  IPAddress VARCHAR(45) NOT NULL,
  Country VARCHAR(100) NULL,
  Region VARCHAR(100) NULL,
  City VARCHAR(100) NULL,
  Latitude DECIMAL(10,7) NULL,
  Longitude DECIMAL(10,7) NULL,
  IsCurrentSession TINYINT(1) NOT NULL DEFAULT 1,
  Success TINYINT(1) NOT NULL DEFAULT 0,
  AttemptedUsername VARCHAR(80) NULL,
  INDEX idx_logins_user_date(UserID, LoginDateTime),
  INDEX idx_login_attempt(IPAddress, LoginDateTime)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ActivityLogs (
  LogID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  UserID BIGINT UNSIGNED NULL,
  Action VARCHAR(100) NOT NULL,
  Module VARCHAR(100) NOT NULL,
  DateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DeviceName VARCHAR(255) NULL,
  IPAddress VARCHAR(45) NULL,
  Details JSON NULL,
  INDEX idx_activity_user_date(UserID, DateTime)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS RememberedDevices (
  DeviceID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  UserID BIGINT UNSIGNED NOT NULL,
  TokenHash CHAR(64) NOT NULL UNIQUE,
  ExpiresAt DATETIME NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_device_user(UserID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS AccountLockouts (
  Username VARCHAR(80) NOT NULL PRIMARY KEY,
  FailedAttempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  LockedUntil DATETIME NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS AccountRecoveryAttempts (
  AttemptKey CHAR(64) NOT NULL PRIMARY KEY,
  FailedAttempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  LockedUntil DATETIME NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PasswordResetRequests (
  RequestID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Username VARCHAR(80) NOT NULL,
  RequestedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Status ENUM('pending','resolved') NOT NULL DEFAULT 'pending',
  INDEX idx_reset_status(Status, RequestedAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS AccountRecoveryAttempts (
  AttemptKey CHAR(64) NOT NULL PRIMARY KEY,
  FailedAttempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  LockedUntil DATETIME NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Workspace invitation codes are stored as hashes, while membership and
-- preferred workspace selection remain centralized in the authentication DB.
CREATE TABLE IF NOT EXISTS WorkspaceMembers (
  OwnerUserID BIGINT UNSIGNED NOT NULL,
  MemberUserID BIGINT UNSIGNED NOT NULL,
  Role ENUM('viewer','editor') NOT NULL DEFAULT 'viewer',
  Status ENUM('active','removed') NOT NULL DEFAULT 'active',
  JoinedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (OwnerUserID, MemberUserID),
  INDEX idx_workspace_member (MemberUserID, Status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS WorkspaceInvitations (
  InvitationID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  OwnerUserID BIGINT UNSIGNED NOT NULL,
  CodeHash CHAR(64) NOT NULL UNIQUE,
  ExpiresAt DATETIME NOT NULL,
  UsedBy BIGINT UNSIGNED NULL,
  UsedAt DATETIME NULL,
  RevokedAt DATETIME NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_workspace_invitation_owner (OwnerUserID, ExpiresAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS WorkspacePreferences (
  UserID BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  OwnerUserID BIGINT UNSIGNED NOT NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS WorkspaceInvitationAttempts (
  UserID BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  FailedAttempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  LockedUntil DATETIME NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
